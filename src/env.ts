import "server-only";
import { z } from "zod";
import { isVapidKeyPair, resolveVapidSubject } from "@/lib/push-rules";
import { siteUrl } from "@/lib/site";

const schema = z
  .object({
    NODE_ENV: z
      .enum(["development", "test", "production"])
      .default("development"),
    DATABASE_URL: z.url(),
    AUTH_SECRET: z
      .string()
      .min(32, "AUTH_SECRET must be at least 32 characters"),
    EDITOR_ALLOWLIST: z.string().optional().default(""),
    RESEND_API_KEY: z.string().optional().default(""),
    EMAIL_FROM: z.string().optional().default("InkBoard <onboarding@resend.dev>"),
    APP_URL: z.url().default("http://localhost:3000"),
    /**
     * How many proxies in front of the app append to X-Forwarded-For.
     * The client IP is taken that many entries from the right, because
     * everything further left is client-controlled. Vercel: 1.
     */
    /** Shared secret for /api/cron/cleanup (Vercel Cron sends it as a Bearer token). */
    CRON_SECRET: z
      .union([z.literal(""), z.string().min(32, "CRON_SECRET must be at least 32 characters")])
      .optional()
      .default(""),
    TRUSTED_PROXY_HOPS: z.coerce.number().int().min(1).max(10).default(1),
    /**
     * Notifications about new poems (docs/PLAN.md, Phase 18; docs/NOTIFICATIONS.md).
     * Both keys or neither: without them the feature is off. Generate with
     * `pnpm exec web-push generate-vapid-keys`. The private key is a secret.
     */
    VAPID_PUBLIC_KEY: z.string().optional().default(""),
    VAPID_PRIVATE_KEY: z.string().optional().default(""),
    /**
     * Contact for push services (RFC 8292 `sub`): an https URL or mailto: on a
     * real domain. Defaults to the site's URL when that is https and not
     * localhost; Apple rejects placeholders and localhost.
     */
    VAPID_SUBJECT: z.string().optional().default(""),
  })
  .superRefine((env, ctx) => {
    // Emails are always really sent, locally too: no key means no sign-in, so
    // fail at startup with a clear message instead. The only exceptions are
    // automated tests: Vitest mocks the email module, and the E2E server
    // records emails in E2E_OTP_OUTBOX (never in production).
    const automatedTest =
      env.NODE_ENV === "test" || (env.NODE_ENV !== "production" && Boolean(process.env.E2E_OTP_OUTBOX));
    if (!env.RESEND_API_KEY && !automatedTest) {
      ctx.addIssue({
        code: "custom",
        path: ["RESEND_API_KEY"],
        message: "RESEND_API_KEY is required to send sign-in emails (set it in .env.local; see docs/DEPLOY.md)",
      });
    }
    if (env.VAPID_PUBLIC_KEY || env.VAPID_PRIVATE_KEY) {
      if (!isVapidKeyPair(env.VAPID_PUBLIC_KEY, env.VAPID_PRIVATE_KEY)) {
        ctx.addIssue({
          code: "custom",
          path: ["VAPID_PUBLIC_KEY"],
          message: "VAPID_PUBLIC_KEY and VAPID_PRIVATE_KEY must both be set, as generated by `web-push generate-vapid-keys`",
        });
      } else if (!resolveVapidSubject(env.VAPID_SUBJECT || undefined, siteUrl())) {
        ctx.addIssue({
          code: "custom",
          path: ["VAPID_SUBJECT"],
          message: env.VAPID_SUBJECT
            ? "VAPID_SUBJECT must be an https URL or a mailto: address on a real domain (not localhost or a placeholder); Apple rejects others"
            : "VAPID_SUBJECT is required when the site URL isn't a public https address (e.g. locally): set an https URL or mailto: on a real domain",
        });
      }
    }
  });

export type Env = z.infer<typeof schema>;

let cached: Env | undefined;

/**
 * Validated server environment. Parsed lazily so that `next build` does not
 * require runtime secrets, but any request that needs them fails loudly.
 */
export function env(): Env {
  if (cached) return cached;
  const parsed = schema.safeParse(process.env);
  if (!parsed.success) {
    const issues = parsed.error.issues
      .map((i) => `  - ${i.path.join(".")}: ${i.message}`)
      .join("\n");
    throw new Error(`Invalid environment configuration:\n${issues}`);
  }
  cached = parsed.data;
  return cached;
}

/** Test helper: re-read process.env on the next env() call. */
export function resetEnvCache(): void {
  cached = undefined;
}

/*
 * Photo storage (docs/PLAN.md, Phase 22). Read separately from env() and only
 * when a photo is stored or served, so the build and every other request run
 * without it, and production without R2 fails at upload time with this message.
 */
const R2_VARS = ["R2_ACCOUNT_ID", "R2_ACCESS_KEY_ID", "R2_SECRET_ACCESS_KEY", "R2_BUCKET"] as const;

export type PhotoStorageConfig =
  | { driver: "r2"; accountId: string; accessKeyId: string; secretAccessKey: string; bucket: string }
  | { driver: "local"; dir: string }
  | { driver: "none"; reason: string };

export function photoStorageConfig(source: NodeJS.ProcessEnv = process.env): PhotoStorageConfig {
  const set = R2_VARS.filter((k) => (source[k] ?? "").trim() !== "");
  if (set.length === R2_VARS.length) {
    const accountId = source.R2_ACCOUNT_ID!.trim();
    if (!/^[a-f0-9]{32}$/i.test(accountId)) {
      return { driver: "none", reason: "R2_ACCOUNT_ID must be the 32-character account ID from the Cloudflare dashboard" };
    }
    return {
      driver: "r2",
      accountId,
      accessKeyId: source.R2_ACCESS_KEY_ID!.trim(),
      secretAccessKey: source.R2_SECRET_ACCESS_KEY!.trim(),
      bucket: source.R2_BUCKET!.trim(),
    };
  }
  if (set.length > 0) {
    const missing = R2_VARS.filter((k) => !set.includes(k));
    return { driver: "none", reason: `R2 is only partly configured: ${missing.join(", ")} ${missing.length === 1 ? "is" : "are"} missing` };
  }
  // A folder on disk: development, Vitest and E2E (never on Vercel, whose disk doesn't last).
  const dir = (source.PHOTO_STORAGE_DIR ?? "").trim();
  if (dir && !source.VERCEL) return { driver: "local", dir };
  if (source.NODE_ENV !== "production" && !source.VERCEL) return { driver: "local", dir: ".storage/dev" };
  return {
    driver: "none",
    reason: "Photo storage isn't configured: set R2_ACCOUNT_ID, R2_ACCESS_KEY_ID, R2_SECRET_ACCESS_KEY and R2_BUCKET (docs/DEPLOY.md)",
  };
}
